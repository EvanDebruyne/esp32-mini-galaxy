def to_px(lon, lat, w, h):
    return ((lon + 180.0) / 360.0 * w, (90.0 - lat) / 180.0 * h)


def raster(polys, w, h):
    img = Image.new("L", (w, h), 0)
    dr = ImageDraw.Draw(img)
    for pts in polys:
        for shift in (-360, 0, 360):   # polygons that poke past +/-180 wrap around
            dr.polygon([to_px(lon + shift, lat, w, h) for lon, lat in pts], fill=255)
    return np.asarray(img, dtype=np.float32) / 255.0


def raster_geojson(path, w, h):
    """Fill every polygon in a GeoJSON file (outer rings on, holes off) at w x h."""
    import json
    img = Image.new("L", (w, h), 0)
    dr = ImageDraw.Draw(img)
    with open(path, encoding="utf-8") as f:
        feats = json.load(f)["features"]
    for ft in feats:
        g = ft["geometry"]
        polys = [g["coordinates"]] if g["type"] == "Polygon" else g["coordinates"]
        for rings in polys:
            for k, ring in enumerate(rings):
                pts = [to_px(lon, lat, w, h) for lon, lat in ring]
                if len(pts) >= 3:
                    dr.polygon(pts, fill=0 if k else 255)
    return np.asarray(img, dtype=np.float32) / 255.0


