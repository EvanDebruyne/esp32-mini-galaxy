def box_in(boxes, lon, lat):
    for lo0, la0, lo1, la1 in boxes:
        if lo0 <= lon <= lo1 and la0 <= lat <= la1:
            return True
    return False


def value_noise3(p, freq, seed):
    """Smooth 3D value noise at points p (N,3) on the unit sphere; no seams anywhere."""
    rng = np.random.default_rng(seed)
    n = int(freq) + 3
    grid = rng.random((n, n, n)).astype(np.float32)
    q = (p * 0.5 + 0.5) * freq + 1.0
    i = np.floor(q).astype(int)
    f = q - i
    f = f * f * (3 - 2 * f)
    out = 0.0
    for dx in (0, 1):
        for dy in (0, 1):
            for dz in (0, 1):
                wgt = (f[:, 0] if dx else 1 - f[:, 0]) * (f[:, 1] if dy else 1 - f[:, 1]) * (f[:, 2] if dz else 1 - f[:, 2])
                out = out + wgt * grid[i[:, 0] + dx, i[:, 1] + dy, i[:, 2] + dz]
    return out


def fbm(p, base, octaves, seed):
    tot, amp, norm = 0.0, 1.0, 0.0
    for o in range(octaves):
        tot = tot + amp * value_noise3(p, base * (2 ** o), seed + o * 17)
        norm += amp
        amp *= 0.5
    return tot / norm


def build():
    # ---- land mask (supersampled, then averaged down) ----
    hw, hh = TW * SS, TH * SS
    ne_land = os.path.join(NE_DIR, "ne_50m_land.geojson")
    if os.path.exists(ne_land):
        land_hi = raster_geojson(ne_land, hw, hh)
        water_hi = raster_geojson(os.path.join(NE_DIR, "ne_50m_lakes.geojson"), hw, hh)
        print("coastlines: Natural Earth 1:50m")
    else:
        land_hi = raster(LAND.values(), hw, hh)
        water_hi = raster(WATER.values(), hw, hh)
        print("coastlines: hand-drawn fallback")
    land_hi = np.clip(land_hi - water_hi, 0, 1)
    land = land_hi.reshape(TH, SS, TW, SS).mean(axis=(1, 3)) > 0.45
    greenland = raster([LAND["greenland"]], hw, hh).reshape(TH, SS, TW, SS).mean(axis=(1, 3)) > 0.3

    # texel centre coordinates
    lons = (np.arange(TW) + 0.5) / TW * 360.0 - 180.0
    lats = 90.0 - (np.arange(TH) + 0.5) / TH * 180.0
    LON, LAT = np.meshgrid(lons, lats)
    phi, lam = np.radians(LAT), np.radians(LON)
    pts = np.stack([np.cos(phi) * np.cos(lam), np.sin(phi), np.cos(phi) * np.sin(lam)], axis=-1).reshape(-1, 3)
    noise = fbm(pts, 6.0, 4, 11).reshape(TH, TW)          # 0..1, for breaking up region edges
    wlon = (fbm(pts, 12.0, 3, 31).reshape(TH, TW) - 0.5) * 16.0   # wobble the region boxes
    wlat = (fbm(pts, 12.0, 3, 47).reshape(TH, TW) - 0.5) * 11.0

    # ---- distance from land, for the coastal shelf ----
    dist = np.full((TH, TW), 99, dtype=np.int32)
    dist[land] = 0
    for d in range(1, 6):
        prev = dist == d - 1
        grown = prev | np.roll(prev, 1, 1) | np.roll(prev, -1, 1)
        grown = grown | np.vstack([grown[1:], grown[-1:]]) | np.vstack([grown[:1], grown[:-1]])
        dist[(dist == 99) & grown] = d

    cls = np.zeros((TH, TW), dtype=np.uint8)
    for y in range(TH):
        for x in range(TW):
            lat, lon, nz = LAT[y, x], LON[y, x], noise[y, x] - 0.5
            wl, wa = lon + wlon[y, x], lat + wlat[y, x]
            if not land[y, x]:
                if lat + nz * 8 > 77 or lat + nz * 6 < -69:
                    cls[y, x] = SEAICE
                elif dist[y, x] <= 1:
                    cls[y, x] = COAST
                elif dist[y, x] <= 3:
                    cls[y, x] = OCEAN
                else:
                    cls[y, x] = DEEP if nz < 0.2 else OCEAN
                continue
            alat = abs(lat) + nz * 10
            if lat < -60 or greenland[y, x] or alat > 78:
                c = ICE
            elif alat > 68:
                c = TUNDRA if nz < 0.1 else ICE
            elif alat > 60:
                c = TUNDRA if alat > 64 else BOREAL
            elif box_in(MOUNTAINS, lon + wlon[y, x] * 0.3, lat + wlat[y, x] * 0.3) and nz > -0.2:
                c = ICE if (lat > 25 and nz > 0.18) else ROCK
            elif box_in(DESERTS, wl, wa):
                c = DESERT if nz > -0.2 else STEPPE
            elif box_in(STEPPES, wl, wa):
                c = STEPPE if nz > -0.15 else GRASS
            elif box_in(JUNGLES, wl, wa):
                c = JUNGLE
            elif alat > 48:
                c = BOREAL if nz > -0.1 else FOREST
            elif abs(lat) < 20:
                c = GRASS if nz > 0.0 else FOREST
            else:
                c = FOREST if nz > -0.12 else GRASS
            cls[y, x] = c

    # ---- city lights (night side only, on the device) ----
    hsh = np.random.default_rng(5).random((TH, TW))
    city = np.zeros((TH, TW), dtype=bool)
    for clon, clat, rad, dens in CITIES:
        dlon = (LON - clon + 180) % 360 - 180
        dd = np.hypot(dlon * np.cos(np.radians(clat)), LAT - clat) / rad
        city |= (hsh < dens * np.clip(1 - dd, 0, 1) ** 0.7) & land
    city &= (cls != ICE)

    landb = cls | (city.astype(np.uint8) << 7)

    # ---- clouds: warped fbm, more cover at the equator and in the storm belts ----
    warp = np.stack([fbm(pts, 3.0, 3, 101 + k) - 0.5 for k in range(3)], axis=-1)
    pw = pts + 0.55 * warp
    pw /= np.linalg.norm(pw, axis=1, keepdims=True)
    cn = fbm(pw, 7.0, 5, 202).reshape(TH, TW)
    belt = (0.10 * np.exp(-((LAT - 6) / 9) ** 2)
            + 0.08 * np.exp(-((np.abs(LAT) - 55) / 12) ** 2)
            - 0.07 * np.exp(-((np.abs(LAT) - 25) / 8) ** 2))
    cv = cn + belt
    lo, hi = 0.55, 0.66
    t = np.clip((cv - lo) / (hi - lo), 0, 1)
    cloud = (t * t * (3 - 2 * t) * 255).astype(np.uint8)
    return landb.astype(np.uint8), cloud


def write_header(landb, cloud, path):
    def table(name, arr):
        rows = []
        for y in range(TH):
            rows.append("  " + ",".join(str(int(v)) for v in arr[y]) + ",")
        return f"static const uint8_t {name}[{TH}][{TW}] = {{\n" + "\n".join(rows) + "\n};\n"

    with open(path, "w", newline="\n") as f:
        f.write("// Generated by sim/make_earth_map.py -- do not edit by hand.\n")
        f.write("// 256 x 128 equirectangular, row 0 = 90N, column 0 = 180W.\n")
        f.write("// EARTH_LAND: low 4 bits = surface class (EARTH_PAL index), bit 7 = city lights.\n")
        f.write("// EARTH_CLOUD: 0..255 cloud cover.\n#pragma once\n#include <stdint.h>\n\n")
        f.write(f"#define EARTH_TW {TW}\n#define EARTH_TH {TH}\n\n")
        f.write(table("EARTH_LAND", landb))
        f.write("\n")
        f.write(table("EARTH_CLOUD", cloud))


def flat_preview(landb, cloud, path):
    pal = np.array([[int(c * 255) for c in p] for p in PALETTE], dtype=np.float32)
    rgb = pal[landb & 15]
    a = (cloud.astype(np.float32) / 255.0)[..., None] * 0.85
    rgb = rgb * (1 - a) + np.array([240, 244, 255], dtype=np.float32) * a
    rgb[(landb & 0x80) > 0] = [255, 200, 90]
    img = Image.fromarray(np.clip(rgb, 0, 255).astype(np.uint8), "RGB")
    nocloud = Image.fromarray(pal[landb & 15].astype(np.uint8), "RGB")
    out = Image.new("RGB", (TW * 3, TH * 3 * 2 + 6), (40, 40, 40))
    out.paste(nocloud.resize((TW * 3, TH * 3), Image.NEAREST), (0, 0))
    out.paste(img.resize((TW * 3, TH * 3), Image.NEAREST), (0, TH * 3 + 6))
    out.save(path)


